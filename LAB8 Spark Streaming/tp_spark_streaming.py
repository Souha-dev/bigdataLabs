import socket, time, threading, random

def start_socket_server_from_file():
    host = "localhost"
    port = 9999

    s = socket.socket()
    s.bind((host, port))
    s.listen(1)

    print("✅ Serveur prêt. Attente connexion Spark...")
    conn, addr = s.accept()
    print("✅ Client connecté :", addr)

    with open("/content/messages.txt", "r", encoding="utf-8") as f:
        lines_file = [line.strip() for line in f if line.strip()]

    while True:
        msg = random.choice(lines_file)
        conn.send((msg + "\n").encode())
        time.sleep(2)

threading.Thread(target=start_socket_server_from_file, daemon=True).start()

