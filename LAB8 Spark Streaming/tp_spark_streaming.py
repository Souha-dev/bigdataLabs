import socket, time, threading

def start_socket_server():
    # Serveur local : envoie des messages en continu
    host = "localhost"
    port = 9999

    s = socket.socket()
    s.bind((host, port))
    s.listen(1)

    conn, addr = s.accept()
    print("Client connecté :", addr)

    messages = [
        "spark streaming dstream",
        "spark spark streaming",
        "big data spark"
    ]

    # Envoi en boucle (toutes les 2 sec)
    while True:
        for msg in messages:
            conn.send((msg + "\n").encode())
            time.sleep(2)

# On lance le serveur dans un thread (pour ne pas bloquer le notebook)
threading.Thread(target=start_socket_server, daemon=True).start()

# ==========================================
# SECTION 3 : SparkContext + StreamingContext
# ==========================================
from pyspark import SparkContext
from pyspark.streaming import StreamingContext

sc = SparkContext.getOrCreate()

# batch interval = 5 secondes
ssc = StreamingContext(sc, 5)

# ==========================
# SECTION 4 : Lecture DStream
# ==========================
lines = ssc.socketTextStream("localhost", 9999)

# ==========================
# SECTION 5 : WordCount
# ==========================
words = lines.flatMap(lambda line: line.split(" "))
pairs = words.map(lambda w: (w, 1))
counts = pairs.reduceByKey(lambda a, b: a + b)

# ==========================
# SECTION 6 : Affichage + Start
# ==========================
counts.pprint()                 # affiche chaque batch
ssc.start()                     # démarre le streaming
ssc.awaitTerminationOrTimeout(30)  # exécute 30 secondes
ssc.stop(stopSparkContext=False)   # stop streaming (garde SparkContext)

